-- Initial Schema Migration for Person CRUD and Courses
-- Compatible with PostgreSQL 16+ and H2 Database

CREATE TABLE person (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_type VARCHAR(31) NOT NULL,
    first_name VARCHAR(255),
    last_name VARCHAR(255),
    email VARCHAR(255)
);

CREATE INDEX idx_person_lastname ON person (last_name);

CREATE TABLE course (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    teacher_id BIGINT,
    CONSTRAINT fk_course_teacher FOREIGN KEY (teacher_id) REFERENCES person (id) ON DELETE SET NULL
);

CREATE TABLE course_students (
    course_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    PRIMARY KEY (course_id, student_id),
    CONSTRAINT fk_course_students_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
    CONSTRAINT fk_course_students_student FOREIGN KEY (student_id) REFERENCES person (id) ON DELETE CASCADE
);
