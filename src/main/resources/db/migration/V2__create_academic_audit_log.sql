-- Flyway Migration V2: Persistent Academic Domain Audit Log
-- Compatible with PostgreSQL 16+ and H2 Database

CREATE TABLE academic_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT,
    event_type VARCHAR(64) NOT NULL,
    description VARCHAR(500) NOT NULL,
    payload_json VARCHAR(2048),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_audit_course_id ON academic_audit_log (course_id);
CREATE INDEX idx_audit_created_at ON academic_audit_log (created_at);
